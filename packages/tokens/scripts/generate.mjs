// Builds everything in @flinbu/seed-tokens from src/source/tokens.json, the single source of truth.
//   node scripts/generate.mjs ts    -> src/generated/tokens.ts (typed data used by createTheme and the CLI)
//   node scripts/generate.mjs css   -> dist/*.css, dist/tokens.json (DTCG), dist/fonts/*
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const src = JSON.parse(fs.readFileSync(path.join(root, "src/source/tokens.json"), "utf8"));
const mode = process.argv[2] || "all";

/* ---------- normalize ---------- */
const colors = src.color.tokens;
const primitives = colors.filter((t) => typeof t.value === "string").map((t) => ({ name: t.name, value: t.value }));
// Primitive lookup: a semantic hex becomes var(--primitive). Prefer neutral and plain scales over aliases like pluto-*.
const rank = (n) => (n.startsWith("neutral-") ? 0 : n.startsWith("b-w-") ? 1 : n.startsWith("pluto-") ? 9 : n.startsWith("alpha-") ? 3 : 2);
const byHex = new Map();
[...primitives].sort((a, b) => rank(a.name) - rank(b.name)).forEach((p) => {
  const k = p.value.toLowerCase().replace(/\s+/g, "");
  if (!byHex.has(k)) byHex.set(k, p.name);
});
const refOf = (v) => byHex.get(String(v).toLowerCase().replace(/\s+/g, "")) || null;

// The accent is themeable: Seed's accent tokens point at --brand-*, which defaults to Seed blue.
const ACCENT = (n) => /accent/.test(n) || /^text-link/.test(n) || /^button-primary(?!-text$)/.test(n);
const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const semantic = colors.filter((t) => typeof t.value !== "string").map((t) => {
  const out = { name: t.name, usage: t.usage || "", light: t.value.light, dark: t.value.dark ?? t.value.light, lightRef: refOf(t.value.light), darkRef: refOf(t.value.dark ?? t.value.light) };
  if (ACCENT(t.name)) {
    for (const m of ["light", "dark"]) {
      const r = out[m + "Ref"];
      const hit = r && /^(blue|pluto)-/.test(r) ? (r.startsWith("pluto-") ? "blue-600" : r) : null;
      if (hit) out[m + "Ref"] = "brand-" + hit.split("-")[1];
    }
  }
  return out;
});
// New in the package: the text and icon color that sits on accent solids (white, or near-black for light brands).
semantic.push({ name: "text-on-accent", usage: "Text and icons on accent solids (bg-accent-solid, button-primary). White by default; createTheme switches it to near-black when the brand is too light for white.", light: "#ffffff", dark: "#ffffff", lightRef: "b-w-white", darkRef: "b-w-white" });
const semNames = new Set(semantic.map((s) => s.name));
const shadows = src.shadow.tokens.map((t) => {
  // Focus rings follow the theme: button-focus-x uses the button-x-focus color token when there is one.
  const m = /^button-focus-(.+)$/.exec(t.name);
  if (m && semNames.has(`button-${m[1]}-focus`)) return { name: t.name, value: t.value.replace(/#[0-9a-f]{3,8}|rgba?\([^)]*\)/i, `var(--button-${m[1]}-focus)`) };
  return { name: t.name, value: t.value };
});
const scale = (k) => src[k].tokens.map((t) => ({ name: t.name, value: String(t.value) }));
const space = scale("spacing"), size = scale("size"), radius = scale("radius"), fontWeight = scale("fontWeight"), duration = scale("duration"), easing = scale("easing");
// New in the package: control heights, so density can be themed without touching spacing.
const control = [{ name: "control-sm", value: "32px" }, { name: "control-md", value: "40px" }, { name: "control-lg", value: "48px" }];
const families = src.type.families; // { primary, titles, mono, display, reading }
const fontFiles = src.type.fonts;
const typeStyles = src.type.groups.flatMap((g) => g.styles.map((s) => ({ name: s.name, group: g.name, family: g.family, fontSize: s.fontSize, lineHeight: String(s.lineHeight), fontWeight: String(s.fontWeight), letterSpacing: s.letterSpacing, usage: s.usage || "" })));
const blue = Object.fromEntries(STEPS.map((s) => [s, primitives.find((p) => p.name === "blue-" + s).value]));

const data = { version: src.version, primitives, semantic, shadows, space, size, radius, fontWeight, duration, easing, control, families, fontFiles, typeStyles, brandDefault: blue };

/* ---------- TS ---------- */
function writeTs() {
  const out = `// Generated by scripts/generate.mjs from src/source/tokens.json. Do not edit.
export const STEPS = ${JSON.stringify(STEPS)} as const;
export const primitives = ${JSON.stringify(Object.fromEntries(primitives.map((p) => [p.name, p.value])), null, 2)} as const;
export const semantic = ${JSON.stringify(semantic, null, 2)} as const;
export const shadows = ${JSON.stringify(Object.fromEntries(shadows.map((p) => [p.name, p.value])), null, 2)} as const;
export const space = ${JSON.stringify(Object.fromEntries(space.map((p) => [p.name, p.value])), null, 2)} as const;
export const size = ${JSON.stringify(Object.fromEntries(size.map((p) => [p.name, p.value])), null, 2)} as const;
export const radius = ${JSON.stringify(Object.fromEntries(radius.map((p) => [p.name, p.value])), null, 2)} as const;
export const control = ${JSON.stringify(Object.fromEntries(control.map((p) => [p.name, p.value])), null, 2)} as const;
export const fontWeight = ${JSON.stringify(Object.fromEntries(fontWeight.map((p) => [p.name, p.value])), null, 2)} as const;
export const duration = ${JSON.stringify(Object.fromEntries(duration.map((p) => [p.name, p.value])), null, 2)} as const;
export const easing = ${JSON.stringify(Object.fromEntries(easing.map((p) => [p.name, p.value])), null, 2)} as const;
export const fonts = ${JSON.stringify(families, null, 2)} as const;
export const typeStyles = ${JSON.stringify(typeStyles, null, 2)} as const;
export const brandDefault = ${JSON.stringify(blue, null, 2)} as const;
`;
  fs.mkdirSync(path.join(root, "src/generated"), { recursive: true });
  fs.writeFileSync(path.join(root, "src/generated/tokens.ts"), out);
}

/* ---------- CSS ---------- */
const HEADER = `/* Seed ${src.version ? "v" + src.version + " " : ""}tokens. Generated from tokens.json, do not edit. https://github.com/flinbu/seed */\n`;
const decl = (n, v) => `  --${n}: ${v};`;
const semVal = (s, m) => (s[m + "Ref"] ? `var(--${s[m + "Ref"]})` : s[m]);
function tokensCss() {
  const rootVars = [
    "  /* Primitives: raw ingredients. Build UI with the semantic tokens below. */",
    ...primitives.map((p) => decl(p.name, p.value)),
    "  /* Brand: the themeable accent scale (Seed blue by default). createTheme() replaces it. */",
    ...STEPS.map((s) => decl("brand-" + s, `var(--blue-${s})`)),
    "  /* Scales */",
    ...[...space, ...size, ...radius, ...control, ...fontWeight, ...duration, ...easing].map((p) => decl(p.name, p.value)),
    ...Object.entries(families).map(([k, v]) => decl("font-" + k, v)),
    "  /* Shadows */",
    ...shadows.map((p) => decl(p.name, p.value)),
  ];
  const light = semantic.map((s) => decl(s.name, semVal(s, "light")));
  const dark = semantic.map((s) => decl(s.name, semVal(s, "dark")));
  return HEADER + `:root {\n${rootVars.join("\n")}\n}

/* Light is the default. Set data-theme="dark" on any element for Dark; data-theme="system" (or no data-theme on <html>) follows the OS. */
:root,
[data-theme="light"] {
  color-scheme: light;
${light.join("\n")}
}

[data-theme="dark"] {
  color-scheme: dark;
${dark.join("\n")}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme]),
  [data-theme="system"] {
    color-scheme: dark;
${dark.map((l) => "  " + l).join("\n")}
  }
}
`;
}
function fontsCss() {
  return HEADER + fontFiles.map((f) => `@font-face {
  font-family: "${f.family}";
  src: url("./fonts/${f.file}") format("woff2");
  font-weight: ${f.weight};
  font-style: ${f.style};
  font-display: swap;
}`).join("\n\n") + "\n";
}
const typeRule = (t) => `font-family: var(--font-${t.family}); font-size: ${t.fontSize}; line-height: ${t.lineHeight}; font-weight: ${t.fontWeight}; letter-spacing: ${t.letterSpacing};${t.group === "Mono" && /label/.test(t.name) ? " text-transform: uppercase;" : ""}`;
function typeCss() {
  return HEADER + "/* Type styles as plain classes, for apps without Tailwind. With Tailwind, tailwind.css defines the same names as utilities. */\n" +
    typeStyles.map((t) => `.${t.name} { ${typeRule(t)} }`).join("\n") + "\n";
}
function tailwindCss() {
  const L = [];
  const add = (k, v) => L.push(`  --${k}: ${v};`);
  L.push("  --color-*: initial;");
  primitives.forEach((p) => add("color-" + p.name, `var(--${p.name})`));
  STEPS.forEach((s) => add("color-brand-" + s, `var(--brand-${s})`));
  add("color-white", "var(--b-w-white)"); add("color-black", "var(--b-w-black)");
  for (const s of semantic) {
    const [kind, ...rest] = s.name.split("-"); const r = rest.join("-");
    if (kind === "bg") add("background-color-" + r, `var(--${s.name})`);
    else if (kind === "text") add("text-color-" + r, `var(--${s.name})`);
    else if (kind === "border") { add("border-color-" + r, `var(--${s.name})`); add("ring-color-" + r, `var(--${s.name})`); add("outline-color-" + r, `var(--${s.name})`); add("divide-color-" + r, `var(--${s.name})`); }
    else add("color-" + s.name, `var(--${s.name})`); // icon-*, button-*: text-icon-secondary, fill-icon-secondary, bg-button-primary
  }
  // Seed's space names only apply to spacing utilities, so Tailwind's max-w-xl, w-sm and friends keep their usual meaning.
  for (const ns of ["padding", "margin", "gap", "inset", "translate", "scroll-margin", "scroll-padding"])
    space.filter((p) => !/-(zero|px)$/.test(p.name)).forEach((p) => add(`${ns}-` + p.name.replace(/^space-/, ""), `var(--${p.name})`));
  for (const ns of ["height", "min-height", "max-height", "width", "min-width", "size"]) control.forEach((p) => add(`${ns}-` + p.name, `var(--${p.name})`));
  L.push("  --radius-*: initial;");
  radius.forEach((p) => add("radius-" + p.name.replace(/^radius-/, ""), `var(--seed-${p.name})`));
  L.push("  --shadow-*: initial;");
  shadows.forEach((p) => add("shadow-" + p.name, `var(--${p.name})`));
  L.push("  --font-*: initial;");
  Object.keys(families).forEach((k) => add("font-" + k, `var(--seed-font-${k})`));
  add("font-sans", `var(--seed-font-primary)`); add("font-serif", `var(--seed-font-reading)`);
  L.push("  --ease-*: initial;");
  easing.forEach((p) => add("ease-" + p.name.replace(/^easing-/, ""), `var(--${p.name})`));
  // Tailwind theme keys can't point at a CSS variable with the same name (it would point at itself), so radius and font go through --seed-* aliases.
  const alias = [...radius.map((p) => `  --seed-${p.name}: var(--${p.name});`), ...Object.keys(families).map((k) => `  --seed-font-${k}: var(--font-${k});`)];
  return HEADER + `/* Seed for Tailwind CSS v4.
   @import "tailwindcss";
   @import "@flinbu/seed-tokens/tailwind.css";
   Every token becomes a utility: bg-primary, text-secondary, border-primary, text-icon-secondary, p-base, gap-xs, mt-lg,
   h-control-md, rounded-control, shadow-elevation-md, font-display, ease-out, and the type styles (label-label-2-medium).
   Space names apply to padding, margin, gap, inset and translate only; max-w-xl, w-sm and size-* keep Tailwind's meaning. */
@import "./tokens.css";
@import "./fonts.css";

/* dark: follows data-theme="dark" on the element or an ancestor, and the OS when data-theme is "system" or missing on <html>. */
@custom-variant dark {
  &:where([data-theme="dark"], [data-theme="dark"] *) {
    @slot;
  }
  @media (prefers-color-scheme: dark) {
    &:where(:root:not([data-theme]) *, [data-theme="system"], [data-theme="system"] *) {
      @slot;
    }
  }
}

/* Re-resolved wherever a theme can change them, so rounded-* and font-* follow [data-brand] scopes. */
:root,
[data-brand],
[data-theme] {
${alias.join("\n")}
}

@theme inline {
${L.join("\n")}
}

${typeStyles.map((t) => `@utility ${t.name} {\n  ${typeRule(t).replace(/; /g, ";\n  ")}\n}`).join("\n")}

@layer base {
  html {
    -webkit-font-smoothing: antialiased;
    -moz-osx-font-smoothing: grayscale;
  }
  body {
    background-color: var(--bg-primary);
    color: var(--text-primary);
    font-family: var(--font-primary);
    font-weight: var(--font-weight-light);
  }
}
`;
}
function dtcg() {
  const out = { $description: "Seed tokens in the W3C Design Tokens format. Semantic colors carry Light as $value and Dark in $extensions.mode.", color: {}, semantic: {}, space: {}, size: {}, radius: {}, shadow: {}, font: {}, fontWeight: {}, duration: {} };
  for (const p of primitives) out.color[p.name] = { $type: "color", $value: p.value };
  for (const s of STEPS) out.color["brand-" + s] = { $type: "color", $value: blue[s], $description: "Themeable accent scale" };
  const ref = (r, v) => (r ? `{color.${r}}` : v);
  for (const s of semantic) out.semantic[s.name] = { $type: "color", $value: ref(s.lightRef, s.light), $description: s.usage, $extensions: { mode: { light: ref(s.lightRef, s.light), dark: ref(s.darkRef, s.dark) } } };
  for (const p of [...space, ...control]) out.space[p.name] = { $type: "dimension", $value: p.value };
  for (const p of size) out.size[p.name] = { $type: "dimension", $value: p.value };
  for (const p of radius) out.radius[p.name] = { $type: "dimension", $value: p.value };
  for (const p of shadows) out.shadow[p.name] = { $type: "shadow", $value: p.value };
  for (const [k, v] of Object.entries(families)) out.font[k] = { $type: "fontFamily", $value: v };
  for (const p of fontWeight) out.fontWeight[p.name] = { $type: "fontWeight", $value: Number(p.value) };
  for (const p of duration) out.duration[p.name] = { $type: "duration", $value: p.value };
  return JSON.stringify(out, null, 2) + "\n";
}
function writeCss() {
  const dist = path.join(root, "dist");
  fs.mkdirSync(path.join(dist, "fonts"), { recursive: true });
  fs.writeFileSync(path.join(dist, "tokens.css"), tokensCss());
  fs.writeFileSync(path.join(dist, "fonts.css"), fontsCss());
  fs.writeFileSync(path.join(dist, "type.css"), typeCss());
  fs.writeFileSync(path.join(dist, "tailwind.css"), tailwindCss());
  fs.writeFileSync(path.join(dist, "index.css"), HEADER + '/* Seed without Tailwind: variables, fonts and type classes. */\n@import "./tokens.css";\n@import "./fonts.css";\n@import "./type.css";\n');
  fs.writeFileSync(path.join(dist, "tokens.json"), dtcg());
  for (const f of fs.readdirSync(path.join(root, "src/fonts"))) fs.copyFileSync(path.join(root, "src/fonts", f), path.join(dist, "fonts", f));
}

if (mode === "ts" || mode === "all") writeTs();
if (mode === "css" || mode === "all") writeCss();
console.log("seed-tokens:", mode, `· ${primitives.length} primitives, ${semantic.length} semantic, ${typeStyles.length} type styles`);
